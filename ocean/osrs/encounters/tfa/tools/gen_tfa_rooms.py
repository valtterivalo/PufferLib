"""Generate tfa_rooms_generated.inc from the fixture room files: 64x64 collision flags, boss spawn, player starts."""

import collections
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
FIXTURES = HERE.parent / "fixtures"
OUT = HERE.parent / "tfa_rooms_generated.inc"
SIZE = 64
BLOCKED = 0x200000
ROOMS = ["GUARDIAN", "BORK", "EZEKIEL", "DREADNOTH", "MOIA", "XARTH", "DAGONHAI", "OCELLUS"]
BOSS_IDS = {
    "GUARDIAN": (16657, 5),
    "BORK": (16640, 4),
    "EZEKIEL": (16652, 3),
    "DREADNOTH": (16665, 5),
    "MOIA": (16667, 3),
    "XARTH": (16684, 3),
    "OCELLUS": (16673, 3),
}


def section(text, name):
    m = re.search(r"^## " + re.escape(name) + r".*?\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    assert m, name
    return m.group(1)


def parse_room(name):
    text = (FIXTURES / f"tfa_{name.lower()}_room.txt").read_text()
    flags = [[0] * SIZE for _ in range(SIZE)]
    for line in section(text, "MAP").splitlines():
        m = re.match(r"^\s*(\d+) (\S{64})$", line)
        if not m:
            continue
        y = int(m.group(1))
        for x, ch in enumerate(m.group(2)):
            flags[y][x] = BLOCKED if ch in "#?" else 0
    for line in section(text, "WALLS").splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[0].isdigit():
            x, y, mask = int(parts[0]), int(parts[1]), int(parts[2], 16)
            if not flags[y][x]:
                flags[y][x] = mask
    npc_id, size = BOSS_IDS[name]
    spawns = re.findall(rf"^{npc_id} (\d+) (\d+) : (\d+)/", section(text, "BOSS SPAWN"), re.M)
    bx, by, _ = max(((int(x), int(y), int(n)) for x, y, n in spawns), key=lambda t: t[2])
    for x in range(bx, bx + size):
        for y in range(by, by + size):
            flags[y][x] = 0
    starts = collections.Counter()
    for m in re.finditer(r"P0@start=\((\d+), (\d+)\) P0@start-10=(\(\d+, \d+\)|None)", text):
        tile = m.group(3) if m.group(3) != "None" else f"({m.group(1)}, {m.group(2)})"
        starts[tuple(int(v) for v in tile.strip("()").split(", "))] += 1
    sx, sy = starts.most_common(1)[0][0]
    assert flags[sy][sx] == 0, (name, sx, sy)
    picks = [(sx, sy)]
    for dx, dy in [(1, 0), (-1, 0), (0, 1), (0, -1), (1, 1), (-1, -1), (2, 0), (-2, 0)]:
        if len(picks) == 4:
            break
        if flags[sy + dy][sx + dx] == 0:
            picks.append((sx + dx, sy + dy))
    assert len(picks) == 4, name
    return flags, (bx, by), picks


def open_room():
    flags = [[BLOCKED if x in (0, SIZE - 1) or y in (0, SIZE - 1) else 0 for x in range(SIZE)] for y in range(SIZE)]
    return flags, (30, 30), [(31, 20), (32, 20), (30, 20), (33, 20)]


def main():
    out = ["/* Generated by tools/gen_tfa_rooms.py from fixtures/tfa_*_room.txt. Do not edit.",
           "   DAGONHAI has no recording yet: an open 64x64 placeholder. */"]
    layouts = []
    for name in ROOMS:
        flags, boss, starts = open_room() if name == "DAGONHAI" else parse_room(name)
        out.append(f"static const uint32_t TFA_FLAGS_{name}[{SIZE * SIZE}] = {{")
        for y in range(SIZE):
            out.append("    " + ", ".join(f"0x{f:x}" for f in flags[y]) + ",")
        out.append("};")
        sx = ", ".join(str(p[0]) for p in starts)
        sy = ", ".join(str(p[1]) for p in starts)
        layouts.append(
            f"    [TFA_ROOM_{name}] = {{ .flags = TFA_FLAGS_{name}, .boss_x = {boss[0]}, .boss_y = {boss[1]},\n"
            f"        .start_x = {{ {sx} }}, .start_y = {{ {sy} }} }},")
    out.append("static const TfaRoomLayout TFA_ROOM_LAYOUTS[TFA_ROOM_COUNT] = {")
    out += layouts
    out.append("};")
    OUT.write_text("\n".join(out) + "\n")


main()
